_SHARED: dict = {}

MODE = "lzo"
TAU_MULTIPLES = (0.0625, 0.125, 0.25, 0.5)
C_GRID = (0.25, 0.5, 1.0, 2.0, 4.0)
SPLIT_FILE = Path(__file__).with_name("step3b_split.json")
SCORED = ("B1", "B2")


def peak_gb() -> float:
    return resource.getrusage(resource.RUSAGE_SELF).ru_maxrss / 1024 ** 2


def statewide_view(problem, X_all, frame, zone_all):
    inputs = replace(problem.inputs, X_B=X_all, units=frame)
    return replace(problem, inputs=inputs, units=np.arange(X_all.shape[0]),
                   zone_of_unit=zone_all)


def arm_label(c: float | None) -> str:
    """``K1`` (``κ = n_A``) for ``c`` None or 1: K2 at ``c = 1`` is K1 and reuses its fits."""
    return "K1" if c is None or c == 1.0 else f"K2_c{c:g}"


def norm_c(c: float | None) -> float | None:
    return None if c is None or c == 1.0 else float(c)


def run_unit(unit: tuple) -> tuple:
    c_mult, sim, region_id, k = unit
    s, args = _SHARED, _SHARED["args"]
    label = arm_label(c_mult)
    out = args.out / label / sim / region_id / f"r{k}"
    if (out / "done.json").exists():
        return label, sim, region_id, k, 0.0
    out.mkdir(parents=True, exist_ok=True)
    start = time.perf_counter()
    data, sets, X = s["data"], s["sets"], s["X"]
    region, ref = s["regions"][region_id], s["refs"][region_id]
    index = list(s["regions"]).index(region_id)
    # Step 4's data: the same seeds and functions (truth by region and replicate).
    truth_rng = np.random.default_rng([args.seed, index, k])
    rng = np.random.default_rng([args.seed, SIMULATIONS.index(sim), index, k])
    problems = {key: build_region(data, region, tables=sets[key]) for key in ("A", *SCORED)}
    joint = build_region(data, region, tables=(*sets["A"], *sets["B1"], *sets["B2"]))
    true_pop = draw_truth(joint, truth_rng)
    draw = (draw_gaussian(joint, true_pop, rng) if sim == "G"
            else draw_bernoulli(joint, true_pop, rng))
    sizes = [len(problems[key].cells) for key in ("A", *SCORED)]
    cuts = np.cumsum([0, *sizes])
    reps = {key: with_tables(problems[key], np.arange(cuts[j], cuts[j + 1]), draw)
            for j, key in enumerate(("A", *SCORED))}
    pA = replace(reps["A"], zone_weight=true_pop.N.astype(float))
    inputs = pA.inputs
    Z = inputs.n_zones
    N_A = float(true_pop.N.sum())
    n_A = int(inputs.n)
    kappa = float(n_A if c_mult is None else c_mult * n_A)
    phi = dirmult_phi(N_A, kappa)
    unit_cells = np.array([j for j, name in enumerate(problems["A"].cells)
                           if name.startswith("unit_type:")])
    shares, N_hat = prior_shares(draw.Y[:, :sizes[0]], unit_cells)
    if sim == "G":
        sigma = region_sigma(pA, args.sigma_alpha, args.prior_sd)
    else:
        blocks = [B[:sizes[0], :sizes[0]] for B in draw.blocks]
        sigma = BlockSigma(blocks, draw.floor[:, :sizes[0]], Z,
                           prior_variance(args.prior_sd, inputs.n, inputs.N))
    sigma_dense = sigma.to_dense()
    area = region_area(pA, sigma)
    views = {key: statewide_view(reps[key], X[key], s["frame"], ref["zone"])
             for key in ("A", *SCORED)}
    engine = pair_engine(area, s["H"], ref["theta"], s["G"],
                         zone_log_bases(ref["logb"], ref["zone"], Z, MODE), s["pairs"],
                         shares, N_A, kappa)
    theta0 = np.zeros(s["G"].shape[1])
    W = N_A / phi
    tag = {"arm": label, "c": 1.0 if c_mult is None else c_mult, "kappa": kappa,
           "phi": phi, "simulation": sim, "region": region_id, "replicate": k}

    kw = {"gtol": args.map_gtol, "max_iter": args.map_max_iter, "optimizer": "m10"}
    previous, rows, start_rows, fit_rows, maps = None, [], [], [], {}
    for m in args.tau_multiples:
        t0 = time.perf_counter()
        tau = m * s["tau_ref_g"]
        fit, starts = fit_starts(engine, theta0, tau, "all4", previous, **kw)
        p_b = engine.probabilities(theta0, fit.U).T
        res = solve_conditional_pairs(X["A"], shares[:, None] * p_b, N_A, W, inputs.targets(),
                                      sigma_dense, tol=args.cond_tol,
                                      max_iter=args.cond_max_iter)
        b1 = transfer_misfit(views["B1"], res.r, "x", "A", "B1")["rms_z"].mean()
        values = [f.objective for f in starts]
        rows.append({**tag, "tau_multiple": m, "tau": tau, **fit.info(),
                     "n_starts": len(starts), "spread": max(values) - min(values),
                     "evaluations_all_starts": sum(f.evaluations for f in starts),
                     "b1_rms_z": float(b1), "seconds_tau": time.perf_counter() - t0})
        start_rows += [{**tag, "tau_multiple": m, **f.info(), "selected": f is fit}
                       for f in starts]
        fit_rows.append({**tag, "tau_multiple": m, "model": "conditional_pairs", **res.info(),
                         "shares_max_abs_dev_from_prior": float(np.abs(res.shares - shares).max())})
        maps[m] = (fit.U, p_b, res)
        previous = fit.U
        logger.info("%s %s %s r%d tau %g: MAP from %s (spread %.2f), B1 %.3f, %.0fs", label, sim,
                    region_id, k, m, fit.start, rows[-1]["spread"], b1, rows[-1]["seconds_tau"])
    chosen = int(np.argmin([r["b1_rms_z"] for r in rows]))
    m_star = args.tau_multiples[chosen]
    for j, r in enumerate(rows):
        r["chosen_b1"] = j == chosen
    U_hat, p_b, res = maps[m_star]

    t0 = time.perf_counter()
    post_rng = np.random.default_rng([args.seed, SIMULATIONS.index(sim), index, k, 1])
    fun = s["fun"]
    sample = pair_posterior_samples(engine, theta0, U_hat, m_star * s["tau_ref_g"], fun,
                                    X["A"], args.draws, post_rng)
    counts = np.zeros(data.weight.size)
    counts[joint.units] = true_pop.counts
    truth = zone_truth(fun, ref["zone"], counts, Z)
    st = interval_stats(sample.samples, truth)
    b1_idx = fun.of("B1")
    b1_logdens = predictive_log_density(sample.samples[:, :, b1_idx],
                                        draw.Y[:, cuts[1]:cuts[2]], draw.var[:, cuts[1]:cuts[2]])
    seconds_post = time.perf_counter() - t0
    frame = pd.DataFrame({
        "zone": np.repeat(np.array(region.pumas), fun.F),
        "cls": np.tile(fun.cls, Z), "functional": np.tile(fun.names, Z),
        "truth": truth.ravel(), **{key: np.asarray(v).ravel() for key, v in st.items()}})
    fitted = fun.of("fitted")
    se = np.full((Z, fun.F), np.nan)
    published = np.full((Z, fun.F), np.nan)
    se[:, fitted] = np.sqrt(draw.var[:, :sizes[0]])
    published[:, fitted] = draw.Y[:, :sizes[0]]
    frame["se"], frame["published"] = se.ravel(), published.ravel()
    frame["direct_cover90"] = np.where(frame["se"].notna(),
                                       np.abs(frame["published"] - frame["truth"])
                                       <= 1.645 * frame["se"], np.nan)
    frame["width90_over_se"] = frame["width90"] / (2 * frame["se"])
    frame["width90_over_truth"] = np.where(frame["truth"] > 0,
                                           frame["width90"] / frame["truth"], np.nan)
    frame = frame.assign(**tag, tau_multiple=m_star)
    frame.to_csv(out / "posterior.csv.gz", index=False)

    se_cells = np.sqrt(inputs.sigma_v)
    parts = {key: [] for key in ("scores", "rare", "misfit", "transfer")}
    for name, pm in (("latent_kern30", res.r), ("latent_kern30:p", shares[:, None] * p_b)):
        scored = score_region(data, views["A"], pm, name, se_cells)
        scored["transfer"] = pd.concat([transfer_misfit(views[key], pm, name, "A", key)
                                        for key in SCORED], ignore_index=True)
        for key in parts:
            parts[key].append(scored[key].assign(**tag, tau_multiple=m_star))
    for key, p in parts.items():
        write_text(out / f"{key}.csv", pd.concat(p, ignore_index=True).to_csv(index=False))
    write_text(out / "tau.csv", pd.DataFrame(rows).to_csv(index=False))
    write_text(out / "starts.csv", pd.DataFrame(start_rows).to_csv(index=False))
    write_text(out / "fits.csv", pd.DataFrame(fit_rows).to_csv(index=False))
    save_npz(out / "map.npz", U=U_hat, tau_multiple=np.array(m_star), shares=shares,
             N_hat=N_hat, N_true=true_pop.N, Y=draw.Y, var=draw.var,
             zones=np.array(region.pumas))
    seconds = time.perf_counter() - start
    write_text(out / "done.json", json.dumps({
        **tag, "seconds": seconds, "seconds_posterior": seconds_post,
        "seconds_map": float(sum(r["seconds_tau"] for r in rows)),
        "chosen_tau_multiple": m_star, "b1_logdens": b1_logdens, "draws": args.draws,
        "negative_variances": sample.negative_variances,
        "seconds_per_draw": sample.seconds_per_draw, "Z": Z, "N_A": N_A, "n_A": n_A,
        "peak_gb": peak_gb()}, default=float))
    logger.info("%s %s %s r%d: done in %.0fs (tau %g, B1 log density %.1f)", label, sim,
                region_id, k, seconds, m_star, b1_logdens)
    return label, sim, region_id, k, seconds


def run_units(units: list, args) -> None:
    if args.workers > 1 and len(units) > 1:
        context = multiprocessing.get_context("fork")
        with ProcessPoolExecutor(max_workers=args.workers, mp_context=context) as pool:
            for label, sim, rid, k, seconds in pool.map(run_unit, units):
                logger.info("unit %s %s %s r%d finished (%.0fs)", label, sim, rid, k, seconds)
    else:
        for unit in units:
            run_unit(unit)


def choose_c(args, sims, chosen) -> dict:
    """Per simulation and region, ``c`` with the largest B1 predictive log
    density summed over the selection replicates."""
    out = {}
    for sim in sims:
        for rid in chosen:
            totals = {}
            for c in args.c_grid:
                vals = []
                for k in range(min(args.c_replicates, args.replicates)):
                    path = args.out / arm_label(c) / sim / rid / f"r{k}" / "done.json"
                    vals.append(json.loads(path.read_text())["b1_logdens"])
                totals[c] = float(np.sum(vals))
            out[f"{sim}/{rid}"] = {"c": max(totals, key=totals.get),
                                   "b1_logdens": {f"{c:g}": v for c, v in totals.items()}}
    return out


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--config", required=True, type=Path)
    parser.add_argument("--regions", required=True, type=Path)
    parser.add_argument("--run", required=True, type=Path, help="stage 1 run directory (z)")
    parser.add_argument("--step1", required=True, type=Path, help="step 1 run root")
    parser.add_argument("--step3", required=True, type=Path, help="step 3 output root")
    parser.add_argument("--step3b", required=True, type=Path, help="step 3b output root")
    parser.add_argument("--step4", required=True, type=Path, help="step 4 output root (its seed)")
    parser.add_argument("--out", required=True, type=Path)
    parser.add_argument("--region", nargs="+", default=None, help="subset of region ids")
    parser.add_argument("--arms", nargs="+", default=["K1", "K2"], choices=["K1", "K2"])
    parser.add_argument("--simulations", nargs="+", default=list(SIMULATIONS),
                        choices=list(SIMULATIONS))
    parser.add_argument("--replicates", type=int, default=10)
    parser.add_argument("--c-grid", type=float, nargs="+", default=list(C_GRID))
    parser.add_argument("--c-replicates", type=int, default=3,
                        help="replicates per region on which K2 chooses c")
    parser.add_argument("--draws", type=int, default=200)
    parser.add_argument("--seed", type=int, default=None,
                        help="default: step 4's (its settings.json), so the data are step 4's")
    parser.add_argument("--basis", default="kern30", choices=list(DEVIATION_BASES))
    parser.add_argument("--tau-multiples", type=float, nargs="+", default=list(TAU_MULTIPLES))
    parser.add_argument("--sigma-alpha", type=float, default=0.01)
    parser.add_argument("--prior-sd", type=float, default=3.0)
    parser.add_argument("--map-gtol", type=float, default=1e-4)
    parser.add_argument("--map-max-iter", type=int, default=20000)
    parser.add_argument("--cond-tol", type=float, default=1e-10)
    parser.add_argument("--cond-max-iter", type=int, default=200)
    parser.add_argument("--workers", type=int, default=1)
    parser.add_argument("--threads", type=int, default=1)
    args = parser.parse_args()
    args.tau_multiples = sorted(args.tau_multiples)
    os.environ.setdefault(OFFLINE_ENV, "1")
    args.out.mkdir(parents=True, exist_ok=True)
    s4 = json.loads((args.step4 / "settings.json").read_text())
    if args.seed is None:
        args.seed = int(s4["seed"])
    elif int(s4.get("seed", args.seed)) != args.seed:
        logger.warning("seed %d differs from step 4's %s: the data will not be step 4's",
                       args.seed, s4.get("seed"))
    record_run(args.out, args)

    config = load_config(args.config)
    regions = {r.id: r for r in load_regions(args.regions)}
    chosen = args.region or list(regions)
    unknown = [r for r in chosen if r not in regions]
    if unknown:
        raise SystemExit(f"unknown regions {unknown}")
    step1 = load_step1(args.step1)
    tau_refs = json.loads((args.step3b / "tau_ref.json").read_text())
    tau_ref_g = float(tau_refs[args.basis]["tau_ref"])
    with stage("load PUMS, tables and replicate weights"):
        data = load_check_data(config)
    with stage("atoms"):
        atoms = load_atoms(data, args.run)
    if not pd.Index(atoms.serial.astype(str)).equals(pd.Index(step1.serial)):
        raise SystemExit("the atoms are not step 1's (SERIALNO order differs)")
    bases_dir = step1.root / "inputs" / "bases"
    H = load_basis(bases_dir, step1.h, atoms, args.run)
    G, basis_info = deviation_basis(args.basis, atoms, bases_dir, args.run)
    del atoms
    split = json.loads(SPLIT_FILE.read_text())
    sets = {"A": transfer_sets(data)["A"], "B1": tuple(split["B1"]), "B2": tuple(split["B2"])}
    X = {key: region_contributions(data, t) for key, t in sets.items()}
    with stage("pair operator over the S1 cells"):
        pairs = PairOperator(X["A"], workers=args.threads)
    base = build_functionals(data, sets)
    ones = sp.csc_matrix(np.ones((base.G.shape[0], 1)))
    fun = Functionals(G=sp.hstack([base.G, ones]).tocsc(), cls=np.append(base.cls, "total"),
                      names=np.append(base.names, "units:total"))
    frame = pd.DataFrame({"SERIALNO": data.units.index.astype(str), "weight": data.weight,
                          "is_group_quarters": data.units["is_group_quarters"].to_numpy()})
    q = data.weight / data.weight.sum()
    refs = {}
    for rid in chosen:
        region = regions[rid]
        theta = np.load(args.step3 / rid / "reference.npz")["theta"]
        logb = log_base(q, region_distance(step1.distances, region.pumas, data.puma),
                        step1.gamma)
        refs[rid] = {"theta": theta, "logb": logb, "zone": zone_of_atoms(region, data.puma)}
    write_text(args.out / "settings.json", json.dumps({
        "mode": MODE, "h": step1.h, "basis": basis_info, "tau_ref_g": tau_ref_g,
        "tau_multiples": args.tau_multiples, "arms": args.arms, "c_grid": args.c_grid,
        "c_replicates": args.c_replicates, "simulations": args.simulations,
        "replicates": args.replicates, "draws": args.draws, "seed": args.seed,
        "step4_seed": s4.get("seed"), "split": {key: list(v) for key, v in sets.items()},
        "functionals": {c: int((fun.cls == c).sum()) for c in np.unique(fun.cls)},
        "map_starts": "all4", "optimizer": "m10", "step1": str(step1.root),
        "step3": str(args.step3), "step3b": str(args.step3b), "step4": str(args.step4),
        "run": str(args.run)}, indent=1, default=str))
    _SHARED.update(data=data, args=args, regions=regions, refs=refs, H=H, G=G, sets=sets, X=X,
                   pairs=pairs, fun=fun, frame=frame, tau_ref_g=tau_ref_g)

    def order(units):
        return sorted(units, key=lambda u: (-len(regions[u[2]].pumas), u[3], u[1], str(u[0])))

    first = []
    if "K1" in args.arms:
        first += [(None, sim, r, k) for sim in args.simulations for r in chosen
                  for k in range(args.replicates)]
    n_sel = min(args.c_replicates, args.replicates)
    if "K2" in args.arms:
        first += [(norm_c(c), sim, r, k) for c in args.c_grid for sim in args.simulations
                  for r in chosen for k in range(n_sel)]
    first = list(dict.fromkeys(first))          # K2 at c = 1 is K1
    logger.info("phase 1: %d units, %d processes", len(first), args.workers)
    run_units(order(first), args)
    if "K2" in args.arms and args.replicates > n_sel:
        choice = choose_c(args, args.simulations, chosen)
        write_text(args.out / "K2_choice.json", json.dumps(choice, indent=1))
        second = [(norm_c(choice[f"{sim}/{r}"]["c"]), sim, r, k) for sim in args.simulations
                  for r in chosen for k in range(n_sel, args.replicates)]
        second = [u for u in dict.fromkeys(second)
                  if not (args.out / arm_label(u[0]) / u[1] / u[2] / f"r{u[3]}" / "done.json").exists()]
        logger.info("phase 2 (K2 at the chosen c): %d units", len(second))
        run_units(order(second), args)
    elif "K2" in args.arms:
        write_text(args.out / "K2_choice.json",
                   json.dumps(choose_c(args, args.simulations, chosen), indent=1))


if __name__ == "__main__":
    main()
