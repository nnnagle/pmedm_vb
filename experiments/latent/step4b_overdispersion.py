"""Step 4b of the latent-population PMEDM: the overdispersed realized level of
model version 4 (``PLAN_latent_step4b.md`` version 1; ``MODEL_latent.qmd``
version 4). A contingency step: run if step 4 finds the posterior
over-confident.

    python experiments/latent/step4b_overdispersion.py --config experiments/embed/stage1_v2.json \
        --regions experiments/latent/regions_tn.json \
        --run $PMEDM_VB_RUNS/embed/stage1_v2/d16_g0.5_r0.01 \
        --step1 $PMEDM_VB_RUNS/latent/step1_sigma --step3 $PMEDM_VB_RUNS/latent/step3 \
        --step3b $PMEDM_VB_RUNS/latent/step3b --step4 $PMEDM_VB_RUNS/latent/step4 \
        --out $PMEDM_VB_RUNS/latent/step4b --workers 16 --threads 1
    python experiments/latent/collect_step4b.py --root $PMEDM_VB_RUNS/latent/step4b \
        --step4 $PMEDM_VB_RUNS/latent/step4 --step3b $PMEDM_VB_RUNS/latent/step3b

**Design** (§4): as step 4 version 2 (regional run, leave-zone-out, ``g`` =
``kern30``, simulations G and S, the same replicates, seeds and realized
truths: the data are generated by step 4's functions with step 4's seed, read
from ``--step4``'s ``settings.json``), with the realized level of model
version 4 (:mod:`pmedm_vb.latent.overdispersed`):

* ``N_A`` known: the region's total, ``Σ_b N_b`` of the realized population;
* prior shares ``π⁰_b = N̂_b / Σ N̂``, ``N̂_b`` the replicate's estimate of the
  zone's unit total from its fitted unit-type cells (truth plus error in G,
  Horvitz–Thompson in S); the true zone totals are not used;
* ``C ~ DirMult(N_A, κ q)`` over (zone, atom) pairs, ``q_bi = π⁰_b p_bi``.

**Arms** (§3):

* ``K1``: ``κ = n_A``, the region's number of records;
* ``K2``: ``κ = c n_A``, ``c ∈ --c-grid`` (``{0.25, 0.5, 1, 2, 4}``), chosen
  per simulation and region by the B1 posterior predictive log density
  (:func:`~pmedm_vb.latent.overdispersed.predictive_log_density`), summed
  over the region's first ``--c-replicates`` replicates (default 3; the plan's
  §6 allows choosing ``c`` on fewer replicates to bound the cost). The other
  replicates run only the chosen ``c``; the selection replicates' fits at the
  chosen ``c`` are reused, and ``c = 1`` is K1 (its fits are shared).

Per (arm, simulation, region, replicate) unit, as step 4: for each ``τ`` the
``U`` MAP refitted under the arm's ``S`` (``all4`` starts, plain L-BFGS, the
lowest exact objective), the conditional PMEDM over pairs (entropy weight
``W = N_A/φ``) and its B1 misfit; ``τ`` chosen by B1 misfit; the Laplace
posterior (``--draws``) of every step 4 functional and of each zone's total
``N_b`` (class ``total``: the zone totals are random in version 4); interval
statistics against the realized truth; the B1 predictive log density; the
realized MAP's point accuracy. Each unit writes
``<out>/<arm>/<simulation>/<region>/r<k>/`` with step 4's files and
``done.json``; ``K2``'s arm directories are ``K2_c<c>``, and the choice of
``c`` is in ``<out>/K2_choice.json``. Finished units are skipped.

Runs offline: ``PMEDM_VB_OFFLINE=1`` is set if the caller has not set it.
"""

